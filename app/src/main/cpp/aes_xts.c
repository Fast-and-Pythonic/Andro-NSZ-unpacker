static const uint8_t RCON[11] = {
   0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

/* ---------- Key expansion ---------- */

static void key_expand(const uint8_t *key, uint32_t *ks)
{
   for (int i = 0; i < 4; i++) {
      ks[i] = ((uint32_t)key[4*i]   << 24)
            | ((uint32_t)key[4*i+1] << 16)
            | ((uint32_t)key[4*i+2] <<  8)
            | ((uint32_t)key[4*i+3]);
   }
   for (int i = 4; i < 44; i++) {
      uint32_t tmp = ks[i-1];
      if (i % 4 == 0) {
         tmp = ((uint32_t)SBOX[(tmp >> 16) & 0xff] << 24)
             | ((uint32_t)SBOX[(tmp >>  8) & 0xff] << 16)
             | ((uint32_t)SBOX[(tmp      ) & 0xff] <<  8)
             | ((uint32_t)SBOX[(tmp >> 24) & 0xff]);
         tmp ^= (uint32_t)RCON[i/4] << 24;
      }
      ks[i] = ks[i-4] ^ tmp;
   }
}

/* ---------- GF(2^8) multiply by 2 ---------- */

static inline uint8_t xtime(uint8_t a)
{
   return (uint8_t)((a << 1) ^ ((a >> 7) ? 0x1b : 0x00));
}

/* ---------- AES-128 encrypt one block ---------- */

static void aes128_encrypt_block(const uint32_t *ks,
                                  const uint8_t  *in,
                                  uint8_t        *out)
{
   uint8_t s[16];
   memcpy(s, in, 16);

   for (int c = 0; c < 4; c++) {
      uint32_t rk = ks[c];
      s[4*c+0] ^= (uint8_t)(rk >> 24);
      s[4*c+1] ^= (uint8_t)(rk >> 16);
      s[4*c+2] ^= (uint8_t)(rk >>  8);
      s[4*c+3] ^= (uint8_t)(rk      );
   }

   for (int round = 1; round <= 10; round++) {
      for (int i = 0; i < 16; i++) s[i] = SBOX[s[i]];

      uint8_t tmp;
      tmp=s[1];  s[1]=s[5];  s[5]=s[9];  s[9]=s[13]; s[13]=tmp;
      tmp=s[2];  s[2]=s[10]; s[10]=tmp;
      tmp=s[6];  s[6]=s[14]; s[14]=tmp;
      tmp=s[15]; s[15]=s[11];s[11]=s[7]; s[7]=s[3];  s[3]=tmp;

      if (round < 10) {
         for (int c = 0; c < 4; c++) {
            uint8_t a0=s[4*c+0], a1=s[4*c+1],
                    a2=s[4*c+2], a3=s[4*c+3];
            s[4*c+0] = xtime(a0)^xtime(a1)^a1^a2^a3;
            s[4*c+1] = a0^xtime(a1)^xtime(a2)^a2^a3;
            s[4*c+2] = a0^a1^xtime(a2)^xtime(a3)^a3;
            s[4*c+3] = xtime(a0)^a0^a1^a2^xtime(a3);
         }
      }

      for (int c = 0; c < 4; c++) {
         uint32_t rk = ks[round*4 + c];
         s[4*c+0] ^= (uint8_t)(rk >> 24);
         s[4*c+1] ^= (uint8_t)(rk >> 16);
         s[4*c+2] ^= (uint8_t)(rk >>  8);
         s[4*c+3] ^= (uint8_t)(rk      );
      }
   }
   memcpy(out, s, 16);
}

/* ---------- GF(2^8) general multiply (for InvMixColumns) ---------- */

static inline uint8_t gmul(uint8_t a, uint8_t b)
{
   uint8_t p = 0;
   for (int i = 0; i < 8; i++) {
      if (b & 1) p ^= a;
      uint8_t hi = a & 0x80;
      a = (uint8_t)(a << 1);
      if (hi) a ^= 0x1b;
      b >>= 1;
   }
   return p;
}

/* ---------- AES-128 decrypt one block ---------- */

static void aes128_decrypt_block(const uint32_t *ks,
                                  const uint8_t  *in,
                                  uint8_t        *out)
{
   uint8_t s[16];
   memcpy(s, in, 16);

   for (int c = 0; c < 4; c++) {
      uint32_t rk = ks[10*4 + c];
      s[4*c+0] ^= (uint8_t)(rk >> 24);
      s[4*c+1] ^= (uint8_t)(rk >> 16);
      s[4*c+2] ^= (uint8_t)(rk >>  8);
      s[4*c+3] ^= (uint8_t)(rk      );
   }

   for (int round = 9; round >= 1; round--) {
      uint8_t tmp;
      tmp=s[13]; s[13]=s[9]; s[9]=s[5];  s[5]=s[1];  s[1]=tmp;
      tmp=s[2];  s[2]=s[10]; s[10]=tmp;
      tmp=s[6];  s[6]=s[14]; s[14]=tmp;
      tmp=s[3];  s[3]=s[7];  s[7]=s[11]; s[11]=s[15]; s[15]=tmp;

      for (int i = 0; i < 16; i++) s[i] = SBOX_INV[s[i]];

      for (int c = 0; c < 4; c++) {
         uint32_t rk = ks[round*4 + c];
         s[4*c+0] ^= (uint8_t)(rk >> 24);
         s[4*c+1] ^= (uint8_t)(rk >> 16);
         s[4*c+2] ^= (uint8_t)(rk >>  8);
         s[4*c+3] ^= (uint8_t)(rk      );
      }

      for (int c = 0; c < 4; c++) {
         uint8_t a0=s[4*c+0], a1=s[4*c+1],
                 a2=s[4*c+2], a3=s[4*c+3];
         s[4*c+0] = gmul(0x0e,a0)^gmul(0x0b,a1)^gmul(0x0d,a2)^gmul(0x09,a3);
         s[4*c+1] = gmul(0x09,a0)^gmul(0x0e,a1)^gmul(0x0b,a2)^gmul(0x0d,a3);
         s[4*c+2] = gmul(0x0d,a0)^gmul(0x09,a1)^gmul(0x0e,a2)^gmul(0x0b,a3);
         s[4*c+3] = gmul(0x0b,a0)^gmul(0x0d,a1)^gmul(0x09,a2)^gmul(0x0e,a3);
      }
   }

   uint8_t tmp;
   tmp=s[13]; s[13]=s[9]; s[9]=s[5];  s[5]=s[1];  s[1]=tmp;
   tmp=s[2];  s[2]=s[10]; s[10]=tmp;
   tmp=s[6];  s[6]=s[14]; s[14]=tmp;
   tmp=s[3];  s[3]=s[7];  s[7]=s[11]; s[11]=s[15]; s[15]=tmp;

   for (int i = 0; i < 16; i++) s[i] = SBOX_INV[s[i]];

   for (int c = 0; c < 4; c++) {
      uint32_t rk = ks[c];
      s[4*c+0] ^= (uint8_t)(rk >> 24);
      s[4*c+1] ^= (uint8_t)(rk >> 16);
      s[4*c+2] ^= (uint8_t)(rk >>  8);
      s[4*c+3] ^= (uint8_t)(rk      );
   }

   memcpy(out, s, 16);
}

/* ---------- GF(2^128) multiply by x (XTS tweak update) ---------- */

static void xts_mul_alpha(uint8_t *t)
{
   uint8_t feedback = (t[15] >> 7) & 1;
   for (int i = 15; i > 0; i--) {
      t[i] = (uint8_t)((t[i] << 1) | (t[i-1] >> 7));
   }
   t[0] = (uint8_t)((t[0] << 1) ^ (feedback ? 0x87 : 0x00));
}

/* ---------- Public API ---------- */

void aes_xts_decrypt(const uint8_t *in,
                     uint8_t       *out,
                     size_t         sector_count,
                     size_t         sector_size,
                     uint64_t       first_sector,
                     const uint8_t *key1,
                     const uint8_t *key2)
{
   uint32_t ks1[44], ks2[44];
   key_expand(key1, ks1);
   key_expand(key2, ks2);

   for (size_t sec = 0; sec < sector_count; sec++) {
      uint64_t sector_num = first_sector + (uint64_t)sec;

      /* Tweak T = AES_K2(sector_num as 128-bit big-endian)
       * Nintendo Switch NCA headers use big-endian sector encoding,
       * matching Python nsz reference (aes128.py AESXTS class). */
      uint8_t tweak_in[16] = {0};
      tweak_in[15] = (uint8_t)(sector_num);
      tweak_in[14] = (uint8_t)(sector_num >>  8);
      tweak_in[13] = (uint8_t)(sector_num >> 16);
      tweak_in[12] = (uint8_t)(sector_num >> 24);
      tweak_in[11] = (uint8_t)(sector_num >> 32);
      tweak_in[10] = (uint8_t)(sector_num >> 40);
      tweak_in[9]  = (uint8_t)(sector_num >> 48);
      tweak_in[8]  = (uint8_t)(sector_num >> 56);

      uint8_t T[16];
      aes128_encrypt_block(ks2, tweak_in, T);

      const uint8_t *sec_in  = in  + sec * sector_size;
      uint8_t       *sec_out = out + sec * sector_size;

      for (size_t b = 0; b < sector_size; b += 16) {
         uint8_t tmp[16], pp[16];
         for (int i = 0; i < 16; i++) tmp[i] = sec_in[b+i] ^ T[i];
         aes128_decrypt_block(ks1, tmp, pp);
         for (int i = 0; i < 16; i++) sec_out[b+i] = pp[i] ^ T[i];
         xts_mul_alpha(T);
      }
   }
}
